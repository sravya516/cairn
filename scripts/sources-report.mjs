// Regenerates the generated tables in CONTENT_SOURCES.md (guide -> sources, card -> sources).
// Verification dates are NEVER generated: existing dates in the file are preserved row by row, new rows get "—".
// Run: npm run sources        (add --check to fail instead of writing, used by tests/CI)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseGuides } from '../src/utils/guide-format.js';

const ROOT = process.cwd();
const FILE = path.join(ROOT, 'CONTENT_SOURCES.md');
const GUIDE = { begin: '<!-- BEGIN:GUIDE-MAP (generated by `npm run sources`; edit only the Last verified column) -->', end: '<!-- END:GUIDE-MAP -->' };
const CARD = { begin: '<!-- BEGIN:CARD-MAP (generated by `npm run sources`; edit only the Last verified column) -->', end: '<!-- END:CARD-MAP -->' };
const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function loadGuides(root = ROOT) {
  const dir = path.join(root, 'src', 'data', 'guides');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.md')).sort()
    .flatMap((f) => parseGuides(fs.readFileSync(path.join(dir, f), 'utf8'), f).guides);
}

export function loadCards(root = ROOT) {
  const dir = path.join(root, 'src', 'data', 'emergency');
  return fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()
    .flatMap((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')));
}

function previousDates(text, markers) {
  const prev = new Map();
  const m = text.match(new RegExp(escRe(markers.begin) + '([\\s\\S]*?)' + escRe(markers.end)));
  if (m) for (const line of m[1].split('\n')) {
    const cells = line.split('|').map((c) => c.trim());
    if (cells.length >= 6 && /^`.+`$/.test(cells[1])) prev.set(cells[1].slice(1, -1), cells[4]);
  }
  return prev;
}

const table = (markers, header, rows) => [markers.begin, header, '|----------|-------|---------|---------------|', ...rows, markers.end].join('\n');

export function renderGuideMap(guides, text) {
  const prev = previousDates(text, GUIDE);
  return table(GUIDE, '| Guide ID | Title | Sources | Last verified |',
    guides.map((g) => `| \`${g.id}\` | ${g.title.replace(/\|/g, '/')} | ${g.sources.map((s) => '`' + s + '`').join(', ')} | ${prev.get(g.id) || '—'} |`));
}
export function renderCardMap(cards, text) {
  const prev = previousDates(text, CARD);
  return table(CARD, '| Card ID | Title | Sources | Last verified |',
    cards.map((c) => `| \`${c.id}\` | ${c.title.replace(/\|/g, '/')} | ${c.sources.map((s) => '`' + s + '`').join(', ')} | ${prev.get(c.id) || '—'} |`));
}

export function updateText(text, guides, cards) {
  let out = text;
  const gBlock = renderGuideMap(guides, out);
  const gRe = new RegExp(escRe(GUIDE.begin) + '[\\s\\S]*?' + escRe(GUIDE.end));
  if (gRe.test(out)) out = out.replace(gRe, () => gBlock);
  else out = out.replace(/(## Guide → source map[\s\S]*?\n\n)(\|[^\n]*\n)+/, (_all, head) => head + gBlock + '\n');
  if (cards) {
    const cBlock = renderCardMap(cards, out);
    const cRe = new RegExp(escRe(CARD.begin) + '[\\s\\S]*?' + escRe(CARD.end));
    if (cRe.test(out)) out = out.replace(cRe, () => cBlock);
    else {
      // First run: add the section right after the guide map.
      const intro = '\n\n## Emergency Now cards → source map\n\n_Generated like the table above. The cards are short summaries of the guides and carry the same safety-critical statements, so they are verified separately._\n\n';
      out = out.replace(GUIDE.end, () => GUIDE.end + intro + cBlock);
    }
  }
  return out;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) {
  const guides = loadGuides();
  const cards = loadCards();
  const before = fs.readFileSync(FILE, 'utf8');
  const after = updateText(before, guides, cards);
  if (process.argv.includes('--check')) {
    if (before !== after) { console.error('CONTENT_SOURCES.md is out of date. Run: npm run sources'); process.exit(1); }
    console.log('CONTENT_SOURCES.md is up to date.');
  } else {
    fs.writeFileSync(FILE, after);
    console.log(`CONTENT_SOURCES.md updated: ${guides.length} guides, ${cards.length} cards.`);
  }
}
